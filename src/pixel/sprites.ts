import { COLORS } from './palette'

/**
 * Sprites como cuadrículas de texto: cada carácter es un píxel lógico.
 * Se dibujan en tiempo de ejecución, sin imágenes externas, y aceptan una
 * paleta propia para que el mismo dibujo sirva en ocho mundos distintos.
 *
 * k tinta · d sombra · s pizarra · m acero · l plata · w blanco · h crema
 * e piel · q piel sombreada · u madera · n madera oscura · o naranja
 * y oro · r rojo · i rosa · g verde · f bosque · c cian · b azul
 * v violeta · p púrpura · t turquesa · z marino
 */
export type SpriteGrid = readonly string[]

export const SPRITE_COLORS: Record<string, string> = {
  k: COLORS.ink,
  d: COLORS.inkSoft,
  s: COLORS.slate,
  m: COLORS.steel,
  l: COLORS.silver,
  w: COLORS.paper,
  h: COLORS.cream,
  e: COLORS.skin,
  q: COLORS.skinShade,
  u: COLORS.wood,
  n: COLORS.woodDark,
  o: COLORS.orange,
  y: COLORS.gold,
  r: COLORS.red,
  i: COLORS.pink,
  g: COLORS.green,
  f: COLORS.forest,
  c: COLORS.cyan,
  b: COLORS.blue,
  v: COLORS.violet,
  p: COLORS.purple,
  t: COLORS.teal,
  z: COLORS.navy,
}

export interface SpriteOptions {
  scale?: number
  flip?: boolean
  palette?: Record<string, string>
  outline?: string | null
}

/** Dibuja un sprite en coordenadas lógicas, con contorno opcional de un píxel. */
export function drawSprite(
  context: CanvasRenderingContext2D,
  grid: SpriteGrid,
  x: number,
  y: number,
  options: SpriteOptions = {},
): void {
  const scale = options.scale ?? 1
  const palette = { ...SPRITE_COLORS, ...options.palette }
  const width = Math.max(...grid.map((row) => row.length))
  const height = grid.length
  const at = (column: number, row: number): string =>
    options.flip ? (grid[row]?.[width - 1 - column] ?? '.') : (grid[row]?.[column] ?? '.')

  if (options.outline) {
    context.fillStyle = options.outline
    for (let row = 0; row < height; row += 1) {
      for (let column = 0; column < width; column += 1) {
        if (at(column, row) !== '.') continue
        const near =
          at(column - 1, row) !== '.' ||
          at(column + 1, row) !== '.' ||
          at(column, row - 1) !== '.' ||
          at(column, row + 1) !== '.'
        if (near) context.fillRect(x + column * scale, y + row * scale, scale, scale)
      }
    }
  }

  for (let row = 0; row < height; row += 1) {
    for (let column = 0; column < width; column += 1) {
      const colour = palette[at(column, row)]
      if (!colour) continue
      context.fillStyle = colour
      context.fillRect(x + column * scale, y + row * scale, scale, scale)
    }
  }
}

